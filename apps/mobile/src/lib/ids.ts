import * as Crypto from 'expo-crypto';

/** UUID v4 generado en el cliente (constitución, Principio I). */
export function newId(): string {
  return Crypto.randomUUID();
}

/**
 * Namespace de los IDs deterministas de CDT (spec 009, research R6):
 * `uuid5(NAMESPACE_URL, 'https://bermudeztech.os/cdt')`. No cambiar: cambiarlo duplicaría
 * renovaciones hechas en dos dispositivos sin conexión.
 */
